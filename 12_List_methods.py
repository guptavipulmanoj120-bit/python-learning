# List methods

# 1 append() -> Add an iteam to the end

fruits1 = ["Apple", "Banana"]

fruits1.append("Mango")

print(fruits1)

# 2 insert() -> Add at a specific position

fruits2 = ["Apple", "Banana", "Orange"]

fruits2.insert(1,"Mango")

print(fruits2) 

# 3 remove() -> Remove by value

fruits3 = ["Apple", "Banana", "Mango"]

fruits3.remove("Banana")

print(fruits3)

