# PYTHON DICTIONARIES

# Example 1: Creating a dictionary

student = {
    "name": "Vipul",
    "age": 21,
    "city": "Mumbai"
}

print(student)


# Example 2: Accessing values

print(student["name"])
print(student["age"])
print(student["city"])


# Example 3: Updating a value

student["age"] = 22

print(student)


# Example 4: Adding a new key-value pair

student["course"] = "Python"

print(student)


# Example 5: Printing a specific value

print(student["name"])