#\n → New Line
print("hello\nworld")

#\t → Tab Space
print("vipul\tsaloni")

#\\ → Print a Backslash
print("vipul\\saloni")

#\' → Single Quote
print("vipul\'gupta")

#\" → Double Quote
print("he said\"hello\"")

#\b → Backspace
print("Helloo\b")

#\r → Carriage Return
print("hello\rgame")

#\a → Alert (Bell)
print("\a")

#\f → Form Feed
print("hello\fworld")

#\v → Vertical Tab
print("hello\vworld")

#Raw Strings (r"")
path = r"C:\Users\Vipul\Documents"

print(path)


