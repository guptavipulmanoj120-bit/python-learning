# Example 6: Function with Parameter


def motivation_line(line):
    print(line)

motivation_line("I don't give up until I win.")


# Example 7: Function with Two Parameters


def add(a, b):
    print(a + b)

add(5, 3)
add(10, 20)
add(1, 9)


# Example 8: Multiplication Function


def multiply(a, b):
    print(a * b)

multiply(2, 6)
multiply(7, 5)
multiply(10, 10)
